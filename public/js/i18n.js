export function normalizeLanguage(value) {
  const code = String(value || '').trim().toLowerCase();

  return languages.some((language) => language.code === code) ? code : defaultLanguage;
}

export function currentLanguage() {
  return normalizeLanguage(window.localStorage.getItem(languageStorageKey));
}

export function setLanguage(code) {
  const normalized = normalizeLanguage(code);

  window.localStorage.setItem(languageStorageKey, normalized);
  document.documentElement.lang = normalized;
  window.dispatchEvent(new CustomEvent('el-promillo-language-change', { detail: { language: normalized } }));

  return normalized;
}

export function t(key, fallback = '') {
  const language = currentLanguage();

  return translations[language]?.[key]
    || translations[defaultLanguage]?.[key]
    || fallback
    || key;
}

export function translatePage(root = document) {
  const language = currentLanguage();
  document.documentElement.lang = language;

  root.querySelectorAll('[data-i18n]').forEach((element) => {
    element.textContent = t(element.dataset.i18n, element.textContent);
  });

  root.querySelectorAll('[data-i18n-placeholder]').forEach((element) => {
    element.setAttribute('placeholder', t(element.dataset.i18nPlaceholder, element.getAttribute('placeholder') || ''));
  });

  root.querySelectorAll('[data-i18n-aria-label]').forEach((element) => {
    element.setAttribute('aria-label', t(element.dataset.i18nAriaLabel, element.getAttribute('aria-label') || ''));
  });
}

export function setupLanguageSelectors(root = document) {
  const selectors = Array.from(root.querySelectorAll('[data-language-select]'));
  const language = currentLanguage();

  document.documentElement.lang = language;

  selectors.forEach((select) => {
    select.value = language;
    select.addEventListener('change', () => {
      setLanguage(select.value);
      translatePage(document);
      selectors.forEach((otherSelect) => {
        otherSelect.value = currentLanguage();
      });
    });
  });

  translatePage(root);
}

export function localeForCurrentLanguage() {
  return {
    de: 'de-CH',
    en: 'en-GB',
    fr: 'fr-CH',
    it: 'it-CH'
  }[currentLanguage()] || 'de-CH';
}
